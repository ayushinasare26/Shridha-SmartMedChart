export function generateMRN(existingPatients: Patient[]): string {
  const highest = existingPatients.reduce((acc, p) => {
    const num = parseInt(p.mrn.replace(/\D/g, ''), 10);
    return isNaN(num) ? acc : Math.max(acc, num);
  }, 94025);
  return `MRN-${highest + 1}`;
}

export function generateToken(department: string, existingPatients: Patient[]): string {
  const prefixMap: Record<string, string> = {
    Cardiology: 'CD',
    'General Medicine': 'GM',
    Orthopedics: 'OR',
    Pediatrics: 'PD',
    Neurology: 'NR',
    Pulmonology: 'PL',
    Dermatology: 'DM',
    'Emergency Triage': 'ER',
  };
  const prefix = prefixMap[department] || 'OPD';
  const deptCount = existingPatients.filter(p => p.caseFile.department === department).length + 1;
  return `${prefix}-${deptCount.toString().padStart(2, '0')}`;
}

export function generateCaseFileId(): string {
  const rand = Math.floor(1000 + Math.random() * 9000);
  return `CF-2026-${rand}`;
}
